    private updateProgress() {
        const progressBar = this.progressBar.node as HTMLElement;
        const progressText = this.progressText.node as HTMLElement;

        if (!progressBar || !progressText) return;

        const progress = (this.currentWordIndex / this.allWords.length) * 100;
        progressBar.style.width = `${progress}%`;
        progressText.textContent = `${this.currentWordIndex} / ${this.allWords.length} Words`;
    }

