    private start() {
        this.isPlaying = true;

        this.renderWordGrid();
        this.updateProgress();
        this.updateCombo();
        this.updateScore(this.score);
        this.updateStreak(this.streak);
        this.updateLives(this.lives);

        if (this.wordInput.node) {
            (this.wordInput.node as HTMLInputElement).focus();
        }

        // Show initial hint
        const firstWord = this.chain.words[0];
        this.updateHint(`Previous word: START | Think: What word goes with "${firstWord[0]}___"?`);
    }

    private renderWordGrid() {
        const wordGrid = this.wordGridContainer.node as HTMLElement;
        if (!wordGrid) return;

        wordGrid.innerHTML = '';
        const words = this.allWords;
        const currentIndex = this.currentWordIndex;

        for (let i = 0; i < words.length; i++) {
            const word = words[i];
            const isCompleted = i < currentIndex;
            const isCurrent = i === currentIndex;
            const isLocked = i > currentIndex;
            const isBonus = i >= this.chain.words.length; // Check against core words length

            let classes = 'word-rung';
            if (isCompleted) classes += ' completed';
            if (isCurrent) classes += ' current';
            if (isLocked) classes += ' locked';
            if (isBonus) classes += ' bonus';

            let wordDisplay = '';
            if (isCompleted) {
                wordDisplay = `<span class="word-display revealed">${word}</span>`;
            } else if (isCurrent) {
                wordDisplay = `<span class="word-display"><span class="first-letter">${word[0]}</span>${'_'.repeat(word.length - 1)}</span>`;
            } else {
                wordDisplay = `<span class="word-display hidden">${'?'.repeat(word.length)}</span>`;
            }

            const rung = document.createElement('div');
            rung.className = classes;
            rung.id = `rung-${i}`;
            rung.setAttribute('data-index', i.toString());
            rung.innerHTML = `
                <span class="rung-number">${i + 1}</span>
                ${wordDisplay}
            `;

            wordGrid.appendChild(rung);
        }

        this.updateRuutPosition();
    }

